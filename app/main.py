"""FastAPI backend: exposes the RAG pipeline over HTTP.

Endpoints:
  POST /api/chat    question + history in, streamed answer out (NDJSON, one JSON object per line)
  GET  /api/health  status, model and data counts
  GET  /docs        interactive API docs (generated by FastAPI)
"""
import json
from contextlib import asynccontextmanager

from fastapi import FastAPI
from fastapi.responses import StreamingResponse
from pydantic import BaseModel, Field

from app.llm import MODEL
from app.pipeline import RAGPipeline

state = {}


@asynccontextmanager
async def lifespan(app):
    """Load the pipeline (chunks, embeddings, reranker) once, when the server starts."""
    state["pipeline"] = RAGPipeline()
    yield


app = FastAPI(title="Real Estate Property Bot API", version="1.0", lifespan=lifespan)


class Message(BaseModel):
    role: str = Field(pattern="^(user|assistant)$")
    content: str = Field(max_length=4000)


class ChatRequest(BaseModel):
    question: str = Field(min_length=1, max_length=1000)
    history: list[Message] = Field(default_factory=list, max_length=20)


def event(kind, **data):
    """One NDJSON line."""
    return json.dumps({"type": kind, **data}, ensure_ascii=False) + "\n"


@app.post("/api/chat")
def chat(req: ChatRequest):
    pipeline = state["pipeline"]
    history = [m.model_dump() for m in req.history]

    def generate():
        try:
            tokens, sources, query = pipeline.stream_answer(req.question, history)
            yield event("meta", sources=sources, query=query)
            for piece in tokens:
                yield event("token", text=piece)
            yield event("done")
        except Exception as e:      # model busy / rate-limited / network error
            print("chat error:", repr(e))
            yield event("error", message="The AI model is unavailable right now. Please try again in a moment.")

    return StreamingResponse(generate(), media_type="application/x-ndjson")


@app.get("/api/health")
def health():
    pipeline = state.get("pipeline")
    return {
        "status": "ok" if pipeline else "loading",
        "model": MODEL,
        "chunks": len(pipeline.retriever.chunks) if pipeline else 0,
        "listings": len(pipeline.listing_filter.listings) if pipeline else 0,
    }